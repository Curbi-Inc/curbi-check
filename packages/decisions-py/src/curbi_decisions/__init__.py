def _shape_ok(r, cfg):
    p = r.get("probabilities")
    if not _is_obj(p):
        return True
    keys = _keys(p)
    if len(keys) != len(r["options"]) or not all(o in p for o in r["options"]) or not all(_is_prob(p[k]) for k in keys):
        return False
    total = 0
    for k in keys:  # left to right, like Array.reduce (the builtin compensates on Python 3.12+ and would differ)
        total = total + p[k]
    if abs(total - 1) > SUM_TOLERANCE:
        return False
    if r["selected"] not in r["options"] or r["selected"] not in cfg["allowed"]:
        return False
    if "score_position" in r:
        pos = r["score_position"]
        mean = 0
        for i, o in enumerate(r["options"]):
            mean = mean + i * p[o]
        if not (_is_num(pos) and 0 <= pos <= len(r["options"]) - 1) or abs(pos - mean) > POSITION_TOLERANCE:
            return False
    return all(p[k] <= p[r["selected"]] + 1e-12 for k in keys)


def _assess(r, cfg):
    if r.get("refused"):
        return ["refused"]
    reasons = []
    if "pin" in cfg and not any(x["provider"] == r["provider"] and x["model"] == r["model"] for x in cfg["pin"]):
        reasons.append("unpinned_model")
    if not _shape_ok(r, cfg):
        return reasons + ["inconsistent"]
    if not _is_obj(r.get("probabilities")):
        return reasons + ["margin_unavailable"]
    p = r["probabilities"]
    top = p[r["selected"]]
    second = max([0] + [p[o] for o in r["options"] if o != r["selected"]])
    if top < cfg["act_at"]:
        reasons.append("below_threshold")
    if top - second < cfg["min_margin"]:
        reasons.append("below_margin")
    return reasons


def _calibration_reasons(cfg, now):
    if not cfg.get("require_calibration"):
        return []
    if "calibration" not in cfg:
        return ["calibration_missing"]
    if not (_is_num(now) and math.isfinite(now)) or now - _date_parse(cfg["calibration"]["measured_at"]) > cfg["max_calibration_age_days"] * DAY:
        return ["calibration_stale"]
    return []


def _unique(a):
    seen, out = set(), []
    for x in a:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


def route(policy, question_id, records, *, now=None):
    cfg = ((policy or {}).get("decisions") or {}).get(question_id)
    if not cfg:
        raise PolicyError("no policy for decision " + str(question_id))
    recs = [r for r in records if r.get("question_id") == question_id]
    fallback = "deny" if cfg["below"] == "deny" else "hand_off"
    if not recs:
        return {"outcome": fallback, "selected": None, "reasons": ["no_record"]}
    cal = _calibration_reasons(cfg, now)
    if "consensus" not in cfg:
        if len(recs) != 1:
            return {"outcome": fallback, "selected": None, "reasons": ["ambiguous_records"]}
        reasons = _unique(_assess(recs[0], cfg) + cal)
        return {"outcome": fallback if reasons else "act", "selected": recs[0]["selected"], "reasons": reasons}
    c = cfg["consensus"]
    models, require, max_divergence = c["models"], c["require"], c["max_divergence"]
    reasons = []
    for r in recs:
        reasons += _assess(r, cfg)
        if r["model"] not in models:
            reasons.append("unpinned_model")
    if len({r["provider"] + "\u0000" + r["model"] for r in recs}) != len(recs):
        reasons.append("duplicate_model")
    voters: dict = {}
    for r in recs:
        if r["selected"] is not None:
            voters.setdefault(r["selected"], [])
            if r["model"] not in voters[r["selected"]]:
                voters[r["selected"]].append(r["model"])
    counts = {k: len(v) for k, v in voters.items()}
    ranked = sorted(counts.items(), key=lambda kv: -kv[1])
    selected = ranked[0][0] if ranked else None
    needed = len(models) if require == "all" else require
    seen = {r["model"] for r in recs}
    missing = [m for m in models if m not in seen]
    if missing and counts.get(selected, 0) < needed:
        why = _unique(reasons + ["consensus_incomplete"] + cal)
        if cfg["below"] == "escalate":
            return {"outcome": "escalate", "selected": selected, "reasons": why, "next_model": missing[0]}
        return {"outcome": fallback, "selected": selected, "reasons": why}
    if counts.get(selected, 0) < needed or (require == "all" and len(counts) > 1):
        reasons.append("consensus_disagreement")
    ps = [r["probabilities"][selected] for r in recs if r["selected"] == selected and _is_obj(r.get("probabilities"))]
    if len(ps) > 1 and max(ps) - min(ps) > max_divergence:
        reasons.append("consensus_divergence")
    why = _unique(reasons + cal)
    return {"outcome": fallback if why else "act", "selected": selected, "reasons": why}


def decision_receipt(*, policy, question_id, records, result, prev=None):
    body = {"object": "curbi.decision-receipt.v1", "v": 1, "question_id": question_id, "checker": CHECKER,
            "policy_digest": digest(policy["decisions"][question_id]),
            "record_digests": [digest(r) for r in records if r.get("question_id") == question_id],
            "outcome": result["outcome"], "selected": result["selected"], "reasons": list(result["reasons"])}
    if result.get("next_model"):
        body["next_model"] = result["next_model"]
    body.update({"prev_receipt_digest": prev, "signed": False, "provider_signed": False,
                 "does_not_prove": "that the vendor computed these probabilities, that they are calibrated, or that the decision is correct"})
    return {**body, "receipt_digest": digest(body)}


def check_action(policy, question_id, result, operation):
    cfg = policy["decisions"][question_id]
    ops = cfg.get("operations") or {}
    needs = [o for o in _keys(ops) if ops[o] == operation]
    if not needs:
        return []
    if result["outcome"] != "act":
        return [{"rule": "decision:not_acted", "why": f"Decision {question_id} was not acted ({result['outcome']}); {operation} needs an acted decision."}]
    if result["selected"] in needs:
        return []
    return [{"rule": "decision:contradicted", "why": f"Decision {question_id} selected \"{result['selected']}\"; {operation} needs {' or '.join(chr(34) + o + chr(34) for o in needs)}."}]
