"""Curbi decision-model adapter (Python port of adapters/decisions/src/decisions.mjs).

The host calls the decision model; this module checks the typed answer against policy before the agent acts on it,
and builds a receipt. No model calls, no vendor keys, no network: arithmetic and comparison on what the host received.

This is a line-for-line port. Parity vectors generated by the JavaScript adapter (tests/vectors.json) must produce
identical records, routes, receipts and digests here. JavaScript semantics are kept on purpose where Python differs:
object key order (integer-like keys first), strict equality (True is not 1), JSON number formatting, and booleans
never counting as numbers.
"""
